def classify(code, floor, area):
    """Return (type, source)."""
    if code in OVERRIDES:
        return OVERRIDES[code], MADE
    num = code[3:]
    base = num.split(".")[0]
    if len(base) == 3 and base[1] == "9":  # EPFL service-room numbering: x92 shafts, x93 WC, x94 circulation
        if area < 3 or base[2] == "2":
            return "technical", PLAN
        if base[2] == "3":
            return "wc", PLAN
        if base[2] == "4":
            if area <= 7:
                return "elevator", PLAN
            if num.endswith((".0", ".10")):
                return "stairs", PLAN
            return ("hall" if area >= 150 else "circulation"), PLAN
    if floor in (1, 2, 3) and num[1:] in UPPER:
        return UPPER[num[1:]], MADE
    if area < 10 or floor == -1:
        return "storage", MADE
    return ("office" if area < 70 else "meeting"), MADE


