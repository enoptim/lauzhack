# ------------------------------------------------------------------ raw data
def fetch():
    RAW.mkdir(exist_ok=True)

    def get(q):
        with urllib.request.urlopen(SEARCH.format(q=urllib.parse.quote(q)), timeout=30) as r:
            return json.load(r)

    fp = [f for f in get("BC")["features"] if f["properties"].get("layer_name") == "batiments"]
    (RAW / "epfl_bc_footprint.geojson").write_text(json.dumps({"type": "FeatureCollection", "features": fp}))
    rooms = {}
    for d in range(10):
        for f in get(f"BC {d}*")["features"]:
            p = f["properties"]
            if p.get("layer_name") == "locaux" and p["label"].startswith("BC "):
                rooms[f["id"]] = f
    (RAW / "epfl_bc_rooms.geojson").write_text(
        json.dumps({"type": "FeatureCollection", "features": list(rooms.values())}))


# ------------------------------------------------------------------ geometry helpers
def ring_area(r):
    return sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(r, r[1:])) / 2


def poly_area(rings):  # outer ring minus holes
    return abs(ring_area(rings[0])) - sum(abs(ring_area(h)) for h in rings[1:])


def centroid(r):
    a = ring_area(r)
    cx = sum((x1 + x2) * (x1 * y2 - x2 * y1) for (x1, y1), (x2, y2) in zip(r, r[1:])) / (6 * a)
    cy = sum((y1 + y2) * (x1 * y2 - x2 * y1) for (x1, y1), (x2, y2) in zip(r, r[1:])) / (6 * a)
    return cx, cy


