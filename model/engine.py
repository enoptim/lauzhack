"""BC building twin engine v2.

Data:  team dir    the data team's files (generated by generate.py, never edited here);
                   set with load(team_dir=...) or env TWIN_TEAM_DATA
       data/model/  our files: people-effect drivers per option, event timing, monthly shares,
                    and placeholders for numbers the data team has not added yet.
                    If a key exists in both, data/team wins.

Chain: energy -> heat coupling -> indoor environment per room -> staff outcomes -> money.
Two views: cash (energy, solar, maintenance, consumables, rent, capex) and economic
(cash + productivity + avoided sick days + time saved). Comfort is a score, never money.

simulate(data, scenario, events_on, overrides) is pure: same inputs, same outputs.
Scenario = list of swaps, later ones win:
    {"group": "lighting", "option": "lighting_mid", "floor": 2, "timing": "now"}
    optional keys: floor, room_id, item_id; timing "now" (default), "end_of_life", or a year
    (e.g. "year": 2). A planned year is pulled forward if the old unit fails first.
Conventions: CHF, real prices, pre-tax (EPFL as owner-occupier), annual finance.
"""
import csv
import math
from collections import defaultdict
from pathlib import Path

INF = float("inf")
PROFILE = {"office": "office_weekday", "meeting": "meeting_weekday", "teaching": "teaching_weekday",
           "common": "common_weekday", "none": None}
POPULATION_TYPES = {"office", "makerspace", "seminar", "computer_lab"}   # default if team adds no flag
STAFF_TYPES = {"office", "makerspace"}

# Engine parameters read from the team's assumptions.csv under another name or unit.
# engine key: (team key, scale). Value, low and high all follow the team's row, so a change there flows through.
FROM_TEAM = {
    # people effects from the literature rows
    "sick_leave_reduction_at_high_ventilation": ("sick_leave_attributable_pct_moderate_outdoor_air", 0.01),  # Milton 2000
    "perf_loss_per_degc_discomfort": ("performance_loss_pct_per_c_above_25c", 0.01),                         # Seppanen 2006
    "printer_enclosure_particle_reduction": ("printer_enclosure_ufp_reduction_pct", 0.01),                    # Azimi 2017
    # roof space for solar
    "pv_max_kwp_with_rooftop_hp": ("pv_max_kwp_with_roof_heat_pumps", 1),
    "pv_max_kwp_without_rooftop_hp": ("pv_max_kwp_without_roof_heat_pumps", 1),
}
# Physical facts per option in the team's options.csv that replace our own drivers. driver: options.csv column
OPTION_FACTS = {"seconds_per_drink": "seconds_per_drink", "humidity_control": "humidity_control",
                "printer_enclosed": "enclosed_filtered"}
INDOOR_GROUPS = {"lighting", "monitors", "computers", "printers_3d", "coffee", "water_heater"}


def _num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def _read(path):
    return list(csv.DictReader(open(path)))


# ---------------------------------------------------------------- loading
HERE = Path(__file__).resolve().parent


def load(team_dir=None, model_dir=None):
    """team_dir: the data team's generated files (env TWIN_TEAM_DATA; default ./data/team,
    or the repo's data/ folder when this file sits in model/ next to it).
    model_dir: our files (env TWIN_MODEL_DATA, default ./data/model)."""
    import os
    default_team = HERE / "data" / "team"
    if not default_team.exists() and (HERE.parent / "data" / "inventory.csv").exists():
        default_team = HERE.parent / "data"           # inside the repo: model/ next to the team's data/
    team = Path(team_dir or os.environ.get("TWIN_TEAM_DATA") or default_team)
    model = Path(model_dir or os.environ.get("TWIN_MODEL_DATA") or HERE / "data" / "model")
    params, ranges, meta = {}, {}, {}
    for src, rows, key in ((model / "model_assumptions.csv", None, "key"), (team / "assumptions.csv", None, "key")):
        for r in _read(src):                       # team file read last, so it wins
            v = _num(r["value"])
            params[r[key]] = v
            lo, hi = _num(r.get("low")), _num(r.get("high"))
            ranges[r[key]] = (lo if lo is not None else v, hi if hi is not None else v)
            meta[r[key]] = {"unit": r.get("unit", ""), "category": r.get("category", "team"),
                            "source": r.get("source", ""), "description": r.get("description", "")}

    for key, (src, scale) in FROM_TEAM.items():
        if src in params:
            ours = meta.get(key, {})
            params[key] = params[src] * scale
            ranges[key] = tuple(x * scale for x in ranges[src])
            meta[key] = {**meta[src], "category": ours.get("category", "team"), "unit": ours.get("unit", meta[src]["unit"])}

    rtypes = {r["type"]: r for r in _read(team / "room_types.csv")}
    rooms = {}
    for r in _read(team / "rooms.csv"):
        t = rtypes[r["type"]]
        flag = t.get("counts_toward_population")
        rooms[r["room_id"]] = {
            "id": r["room_id"], "floor": int(r["floor"]), "type": r["type"], "area": float(r["area_m2"]),
            "seats": int(r["seats"]), "heated": int(r["heated"]), "cooled": int(r["cooled"]),
            "profile": PROFILE.get(t["schedule"]),
            "lighting_hours": float(t["lighting_hours_per_workday"]), "lighting_days": t["lighting_days"],
            "counts": int(flag) if flag not in (None, "") else int(r["type"] in POPULATION_TYPES),
        }
    sched = defaultdict(lambda: [0.0] * 24)
    for r in _read(team / "schedule.csv"):
        for k, v in r.items():
            if k not in ("hour", "source"):
                sched[k][int(r["hour"])] = float(v)

    options = {}
    for r in _read(team / "options.csv"):
        o = {k: (_num(v) if _num(v) is not None else v) for k, v in r.items()}
        for k, v in o.items():
            if v == "" or v is None:
                o[k] = None
        options[r["option_id"]] = o
    for r in _read(model / "option_drivers.csv"):
        options[r["option_id"]]["drivers"] = {k: _num(v) for k, v in r.items() if k not in ("option_id", "notes") and _num(v) is not None}
    for o in options.values():
        o.setdefault("drivers", {})
        for drv, col in OPTION_FACTS.items():
            if o.get(col) is not None:
                o["drivers"][drv] = o[col]

    items = []
    for r in _read(team / "inventory.csv"):
        items.append({"id": r["item_id"], "room": r["room_id"], "floor": int(r["floor"]), "group": r["group"],
                      "option": r["option_id"], "units": int(r["units"]), "age": _num(r["age_years"]),
                      "serves": r["serves"]})

    timing = {r["event_id"]: r for r in _read(model / "events_timing.csv")}
    events = {}
    for r in _read(team / "events.csv"):
        t = timing.get(r["event_id"], {})
        sy = r.get("start_year") or t.get("start_year") or 1
        ey = r.get("end_year") if r.get("end_year") not in (None, "") else t.get("end_year")
        events[r["event_id"]] = {
            "id": r["event_id"], "name": r["name"], "description": r.get("description", ""),
            "param": r["parameter"], "change": r["change"],
            "value": float(r["value"]), "months": _event_months(r),
            "start_year": int(float(sy)), "end_year": int(float(ey)) if ey not in (None, "") else None,
            "kind": r.get("kind") or t.get("kind", "annual"),
        }
    monthly = _read(team / "monthly.csv") if (team / "monthly.csv").exists() else _read(model / "monthly.csv")
    monthly = [{k: float(v) for k, v in m.items() if k != "source"} for m in monthly]

    data = {"params": params, "ranges": ranges, "param_meta": meta, "rooms": rooms, "schedule": dict(sched),
            "options": options, "items": items, "events": events, "monthly": monthly}
    _precompute(data)
    return data


def _precompute(data):
    rooms = data["rooms"]
    data["desks"] = sum(r["seats"] for r in rooms.values() if r["type"] in STAFF_TYPES)
    data["teaching_seats"] = sum(r["seats"] for r in rooms.values() if r["type"] in ("seminar", "computer_lab"))
    data["floor_vent_area"] = defaultdict(float)
    for r in rooms.values():
        if r["heated"]:
            data["floor_vent_area"][r["floor"]] += r["area"]
    data["vent_items"] = {i["id"]: int(i["serves"].split()[-1]) for i in data["items"] if i["group"] == "ventilation"}
    data["blinds_room"] = {i["room"]: i["id"] for i in data["items"] if i["group"] == "blinds"}
    data["by_room_group"] = {(i["room"], i["group"]): i["id"] for i in data["items"]}
    data["item_by_id"] = {i["id"]: i for i in data["items"]}


def baseline(data):
    return {i["id"]: i["option"] for i in data["items"]}


# ---------------------------------------------------------------- scenario resolution
def served_floor(item):
    """Ventilation sits in the basement or on the roof but serves a floor; swaps by floor follow what it serves."""
    return int(item["serves"].split()[-1]) if item["serves"].startswith("floor") else item["floor"]


def resolve(data, scenario):
    """Scenario swaps -> {item_id: (option_id, timing)} for items that change."""
    out = {}
    for sw in scenario or []:
        opt = data["options"][sw["option"]]
        for i in data["items"]:
            if i["group"] != opt["group"]:
                continue
            if "floor" in sw and served_floor(i) != sw["floor"]:
                continue
            if "room_id" in sw and i["room"] != sw["room_id"]:
                continue
            if "item_id" in sw and i["id"] != sw["item_id"]:
                continue
            if sw["option"] == i["option"]:
                out.pop(i["id"], None)
            else:
                timing = sw.get("year", sw.get("timing", "now"))
                out[i["id"]] = (sw["option"], int(timing) if isinstance(timing, (int, float)) else timing)
    return out


def _life(o):
    return o["lifetime_years"] if o["lifetime_years"] else INF


def item_plan(data, item, choice, horizon, remaining=None):
    """Install timeline [(time, option, kind)].

    Current units are replaced like-for-like when they die; an upgrade goes in now or when the
    current unit dies. Deterministic runs use nominal lifetimes (overdue units go at time 0, as a
    planned replacement). A Monte Carlo future passes `remaining` (the unit's sampled remaining
    life); then the original unit's death is a surprise failure (kind "failure", which costs the
    emergency premium), while later replacements of new units are planned."""
    cur = data["options"][item["option"]]
    random_failure = remaining is not None
    if remaining is None:
        remaining = max(0.0, _life(cur) - (item["age"] or 0)) if _life(cur) != INF else INF
    up_t, pulled = None, False
    if choice and isinstance(choice[1], int):          # phased: upgrade at time up_t (end of year up_t)
        up_t = choice[1]
        if random_failure and remaining != INF and math.ceil(remaining) <= up_t:
            # The original unit breaks first, or at that very moment: the upgrade goes in when it breaks,
            # as an emergency (kind "failure", pays the premium), like a like-for-like replacement would.
            up_t, pulled = int(math.ceil(remaining)), True
        elif remaining < up_t:                         # deterministic: the old unit is kept running until then
            remaining = up_t
    elif choice:
        up_t = 0 if choice[1] == "now" else (remaining if remaining != INF else 0)
        up_t = int(math.ceil(up_t)) if up_t != INF else None
        pulled = random_failure and choice[1] == "end_of_life"
    installs, active, end, original = [], item["option"], remaining, True
    while True:
        cand_up = up_t if (up_t is not None and up_t < horizon) else None
        cand_eol = int(math.ceil(end)) if end < horizon else None
        if cand_up is None and cand_eol is None:
            return installs
        if cand_up is not None and (cand_eol is None or cand_up <= cand_eol):
            kind = "failure" if (pulled and original) else "planned"
            active, up_t, original = choice[0], None, False
            installs.append((cand_up, active, kind))
            end = cand_up + _life(data["options"][active])
        else:
            installs.append((cand_eol, active, "failure" if (random_failure and original) else "planned"))
            original = False
            end = cand_eol + _life(data["options"][active])


def active_at(item, installs, year):
    cur = item["option"]
    for t, o, _ in installs:
        if t <= year - 1:
            cur = o
    return cur


def pv_units(data, sel):
    """Coupling: the lake-water heat pump frees the roof, so more solar fits."""
    p = data["params"]
    lake = any(data["options"][o]["option_id"] == "heating_cooling_premium" for o in sel.values())
    return p["pv_max_kwp_without_rooftop_hp"] if lake else p["pv_max_kwp_with_rooftop_hp"]


def units_of(data, item, option_id, sel):
    if item["group"] == "solar_pv" and option_id != item["option"]:
        return pv_units(data, sel)
    return item["units"]


# ---------------------------------------------------------------- one year's context
def year_context(data, year, events_on, overrides):
    p = {**data["params"], **overrides}
    ctx = {"params": p, "staff": p["headcount_staff"], "price_mult": 1.0,
           "cooling_mult": 1.0, "heating_mult": 1.0}
    for ev in events_on:
        if isinstance(ev, dict):     # a sampled future: same event, its own timing
            e = {**data["events"][ev["id"]], **{k: ev[k] for k in ("start_year", "end_year") if k in ev}}
        else:
            e = data["events"][ev]
        if e["kind"] != "annual" or year < e["start_year"] or (e["end_year"] is not None and year > e["end_year"]):
            continue
        months = _months(e)
        if e["param"] == "headcount_staff":
            ctx["staff"] = ctx["staff"] + e["value"] if e["change"] == "add" else ctx["staff"] * e["value"]
        elif e["param"] == "electricity_price_chf_kwh":
            ctx["price_mult"] *= 1 + (e["value"] - 1) * len(months) / 12
        elif e["param"] == "cooling_demand_kwh_m2_year":
            ctx["cooling_mult"] *= 1 + (e["value"] - 1) * sum(data["monthly"][m - 1]["cooling_share"] for m in months)
        elif e["param"] == "heating_demand_kwh_m2_year":
            ctx["heating_mult"] *= 1 + (e["value"] - 1) * sum(data["monthly"][m - 1]["heating_share"] for m in months)
    ctx["price"] = p["electricity_price_chf_kwh"] * ctx["price_mult"]
    ctx["staff_ratio"] = ctx["staff"] / p["headcount_staff"]
    ctx["attendance"] = p["daily_attendance_share"]
    return ctx


def _event_months(r):
    """Months an event applies to. Team format: `months` like "6;7;8", empty = all year.
    Older format: start_month + duration_days."""
    if "months" in r:
        return [int(float(m)) for m in r["months"].split(";") if m.strip()] or list(range(1, 13))
    d = _num(r.get("duration_days")) or 365
    n = max(1, min(12, round(d / 30.4)))
    return [((int(float(r["start_month"])) - 1 + k) % 12) + 1 for k in range(n)]


def _months(e):
    return e["months"]


def room_people(data, ctx, room, hour, profile_override=None):
    """People in a room at an hour on a typical workday."""
    prof = profile_override or room["profile"]
    if not prof:
        return 0.0
    share = data["schedule"][prof][hour]
    att_scale = ctx["attendance"] / max(data["schedule"]["office_weekday"])
    if room["type"] in STAFF_TYPES:      # staff spread over desks; more staff = denser offices
        return room["seats"] / data["desks"] * ctx["staff"] * share * att_scale
    if room["type"] in ("seminar", "computer_lab"):
        return room["seats"] * share
    return room["seats"] * share * ctx["staff_ratio"]      # meeting, kitchen, lounge, cafe


# ---------------------------------------------------------------- layer 1: energy
def energy(data, ctx, sel, ref_gains=None):
    p = ctx["params"]
    wd = p["workdays_per_year"]
    o_ = data["options"]
    staff_present = ctx["staff"] * ctx["attendance"]
    daily_people = staff_present + data["teaching_seats"] * p["student_daily_share"]
    by_item, by_group = {}, defaultdict(float)
    consumables = 0.0
    group_units = defaultdict(float)
    for i in data["items"]:
        group_units[i["group"]] += i["units"]

    for i in data["items"]:
        o = o_[sel[i["id"]]]
        g = i["group"]
        if g in ("heating_cooling", "solar_pv"):
            continue
        u = units_of(data, i, o["option_id"], sel)
        if g == "lighting":
            room = data["rooms"][i["room"]]
            days = wd if room["lighting_days"] == "workdays" else 365
            on_h = room["lighting_hours"] * days
            sav = (o["control_savings_pct"] or 0) / 100
            dl = o["drivers"].get("daylight_savings_pct", 0) / 100
            if dl:     # coupling: blinds decide how much daylight reaches the sensors
                b = data["blinds_room"].get(i["room"])
                factor = o_[sel[b]]["drivers"].get("daylight_factor", 1.0) if b else 1.0
                sav -= dl * (1 - factor)
        else:
            days = wd if o["operating_days"] == "workdays" else 365
            on_h = (o["hours_on_per_day"] or 0) * days
            sav = (o["control_savings_pct"] or 0) / 100
        kwh = u * ((o["power_on_w"] or 0) * on_h * (1 - sav) + (o["standby_w"] or 0) * (8760 - on_h)) / 1000
        if g in ("monitors", "computers"):
            kwh *= ctx["staff_ratio"]           # new lab brings its own devices
        if o["energy_per_use_wh"]:              # per-use part, shared by the group by units
            share = u / group_units[g]
            uses = o["uses_per_person_day"] * daily_people * wd * share
            kwh += o["energy_per_use_wh"] * uses / 1000
            consumables += (o["consumable_chf_per_use"] or 0) * uses
        if g == "servers":
            kwh += kwh / o["cooling_efficiency"]
        by_item[i["id"]] = kwh
        by_group[g] += kwh

    other = p["other_electricity_kwh_m2_year"] * p["floor_area_m2"]
    by_group["other"] = other
    people_h = (ctx["staff"] * sum(data["schedule"]["office_weekday"]) * ctx["attendance"] / max(data["schedule"]["office_weekday"])
                + data["teaching_seats"] * sum(data["schedule"]["teaching_weekday"])) * wd
    gains = sum(by_group[g] for g in INDOOR_GROUPS) + other + people_h * p["person_heat_w"] / 1000

    th = thermal(data, ctx, sel, 0.0 if ref_gains is None else gains - ref_gains)
    by_group["heating_cooling"] = th["hp_kwh"]
    hc_item = next(i for i in data["items"] if i["group"] == "heating_cooling")
    by_item[hc_item["id"]] = th["hp_kwh"]

    pv = next(i for i in data["items"] if i["group"] == "solar_pv")
    po = o_[sel[pv["id"]]]
    gen = units_of(data, pv, po["option_id"], sel) * (po["generation_kwh_per_unit_year"] or 0)
    total = sum(v for k, v in by_group.items())
    self_used = min(gen * p["pv_self_consumption_share"], total)
    return {"total_kwh": total, "grid_kwh": total - self_used, "pv_kwh": gen, "pv_export_kwh": gen - self_used,
            "by_group": dict(by_group), "by_item": by_item, "internal_gains_kwh": gains, "thermal": th,
            "consumables_chf": consumables, "daily_people": daily_people}


def thermal(data, ctx, sel, delta_gains):
    p = ctx["params"]
    o_ = data["options"]
    # heat recovery, weighted by the heated area each ventilation item serves
    hr_w = area_w = 0.0
    for iid, floor in data["vent_items"].items():
        a = data["floor_vent_area"][floor] * data["item_by_id"][iid]["units"]
        hr_w += a * (o_[sel[iid]]["heat_recovery_pct"] or 50) / 100
        area_w += a
    hr = hr_w / area_w
    s = p["ventilation_share_of_heating"]
    heat_factor = (1 - s) + s * (1 - hr) / 0.5
    # solar gains, weighted by window count per blinds option
    red_w = n = 0.0
    for room, iid in data["blinds_room"].items():
        u = data["item_by_id"][iid]["units"]
        red_w += u * (o_[sel[iid]]["solar_gain_reduction_pct"] or 45) / 100
        n += u
    red = red_w / n
    sc = p["solar_share_of_cooling"]
    cool_factor = (1 - sc) + sc * (1 - red) / (1 - 0.45)

    H = p["heating_demand_kwh_m2_year"] * p["heated_area_m2"] * heat_factor * ctx["heating_mult"]
    C = p["cooling_demand_kwh_m2_year"] * p["cooled_area_m2"] * cool_factor * ctx["cooling_mult"]
    cooled_share = p["cooled_area_m2"] / p["heated_area_m2"]
    heat = cool = 0.0
    for m in data["monthly"]:
        Hm, Cm = H * m["heating_share"], C * m["cooling_share"]
        dq = delta_gains / 12
        if Hm + Cm == 0:
            continue
        heat += max(0.0, Hm - p["internal_gain_heating_offset"] * dq * Hm / (Hm + Cm))
        cool += max(0.0, Cm + dq * cooled_share * Cm / (Hm + Cm))
    hc = o_[sel[next(i["id"] for i in data["items"] if i["group"] == "heating_cooling")]]
    return {"heating_kwh_th": heat, "cooling_kwh_th": cool, "heat_recovery": hr, "solar_reduction": red,
            "hp_kwh": heat / hc["heating_efficiency"] + cool / hc["cooling_efficiency"]}


# ---------------------------------------------------------------- layer 2: indoor environment
def environment(data, ctx, sel, cooling_kwh_th, cooling_ref, profile=None, people_override=None):
    """Per-room peak CO2 and per-floor ventilation capacity."""
    p = ctx["params"]
    o_ = data["options"]
    floor_air = defaultdict(float)
    floor_dcv = defaultdict(lambda: 1)
    for iid, floor in data["vent_items"].items():
        o = o_[sel[iid]]
        floor_air[floor] += data["item_by_id"][iid]["units"] * o["airflow_m3h"]
        floor_dcv[floor] = min(floor_dcv[floor], int(o["drivers"].get("co2_control", 0)))
    floor_pop = defaultdict(float)
    if people_override is not None:
        peak = {r: people_override.get(r, 0.0) for r in data["rooms"]}
    else:
        key = (ctx["staff"], ctx["attendance"], profile)
        cache = data.setdefault("_peaks", {})
        if key not in cache:
            cache[key] = {r["id"]: max(room_people(data, ctx, r, h, profile) for h in range(24)) for r in data["rooms"].values()}
        peak = cache[key]
    for r in data["rooms"].values():
        if r["counts"]:
            floor_pop[r["floor"]] += peak[r["id"]]
    cap = {f: floor_air[f] / p["fresh_air_m3h_per_person"] for f in floor_air}
    load_ratio = cooling_kwh_th / cooling_ref if cooling_ref > 0 else 1.0
    rooms = {}
    for r in data["rooms"].values():
        f = r["floor"]
        if not r["heated"] or f not in floor_air or peak[r["id"]] <= 0:
            continue
        air_lps = floor_air[f] * r["area"] / data["floor_vent_area"][f] / 3.6
        lpp = air_lps / peak[r["id"]]
        co2 = p["co2_outdoor_ppm"] + p["co2_generation_lps_per_person"] * 1e6 / lpp
        if floor_dcv[f] and floor_pop[f] <= cap[f]:          # demand control moves air to where people are
            co2 = min(co2, p["co2_dcv_target_ppm"])
            lpp = max(lpp, p["co2_generation_lps_per_person"] * 1e6 / (p["co2_dcv_target_ppm"] - p["co2_outdoor_ppm"]))
        b = data["blinds_room"].get(r["id"])
        red = (o_[sel[b]]["solar_gain_reduction_pct"] / 100) if b else 0.45
        sc = p["solar_share_of_cooling"]
        overheat = (p["summer_overheating_base_degc"] * ((1 - sc) + sc * (1 - red) / 0.55) * load_ratio) if r["cooled"] else 0.0
        rooms[r["id"]] = {"people_peak": peak[r["id"]], "lps_per_person": lpp, "co2_ppm": co2, "overheat_degc": overheat}
    return {"rooms": rooms, "floor_capacity_people": cap, "floor_population_peak": dict(floor_pop)}


# ---------------------------------------------------------------- layer 3: staff outcomes
def _weighted(pairs):
    w = sum(x for x, _ in pairs)
    return sum(x * v for x, v in pairs) / w if w else 0.0


def office_air_per_person(data, env):
    """Outdoor air per person at the busiest hour, desk-weighted over offices and the makerspace (L/s)."""
    E = env["rooms"]
    return _weighted([(r["seats"], E[r["id"]]["lps_per_person"]) for r in data["rooms"].values()
                      if r["type"] in STAFF_TYPES and r["seats"] > 0 and r["id"] in E])


def _sick_factor(p, lpp):
    """Relative sick leave at this ventilation (Milton 2000): 1 at the reference rate, lower with more air."""
    f = max(-0.5, min(1.0, (lpp - p["sick_vent_ref_lps"]) / (p["sick_vent_high_lps"] - p["sick_vent_ref_lps"])))
    return 1 - p["sick_leave_reduction_at_high_ventilation"] * f


def outcomes(data, ctx, sel, env):
    p = ctx["params"]
    o_ = data["options"]
    R = data["rooms"]

    def drv(room_id, group, key, default):
        iid = data["by_room_group"].get((room_id, group))
        return o_[sel[iid]]["drivers"].get(key, default) if iid else default

    def co2_loss(c):
        return p["perf_loss_per_100ppm_co2"] * max(0.0, c - p["co2_no_effect_below_ppm"]) / 100

    desk_rooms = [r for r in R.values() if r["type"] in STAFF_TYPES and r["seats"] > 0 and r["id"] in env["rooms"]]
    meet_rooms = [r for r in R.values() if r["type"] == "meeting" and r["id"] in env["rooms"]]
    teach_rooms = [r for r in R.values() if r["type"] in ("seminar", "computer_lab") and r["id"] in env["rooms"]]
    E = env["rooms"]
    m = p["meeting_time_share"]
    loss_co2 = (1 - m) * _weighted([(r["seats"], co2_loss(E[r["id"]]["co2_ppm"])) for r in desk_rooms]) \
        + m * _weighted([(r["seats"], co2_loss(E[r["id"]]["co2_ppm"])) for r in meet_rooms])
    overheat = _weighted([(r["seats"], E[r["id"]]["overheat_degc"]) for r in desk_rooms])
    lq = _weighted([(r["seats"], drv(r["id"], "lighting", "lighting_quality", 0.5)) for r in desk_rooms])
    sq = _weighted([(r["seats"], drv(r["id"], "monitors", "screen_quality", 0.5)) for r in desk_rooms])
    gc = _weighted([(r["seats"], drv(r["id"], "blinds", "glare_control", 0.5)) for r in desk_rooms])
    strain = 1 - (0.6 * sq + 0.4 * gc)
    maker = [r for r in desk_rooms if r["type"] == "makerspace"]
    cut = p["printer_enclosure_particle_reduction"]
    open_share = _weighted([(r["seats"], 1 - cut * drv(r["id"], "printers_3d", "printer_enclosed", 1)) for r in maker]) \
        * sum(r["seats"] for r in maker) / data["desks"]
    loss = {
        "co2": loss_co2,
        "overheating": p["perf_loss_per_degc_discomfort"] * overheat * p["overheating_season_share"],
        "lighting": p["perf_loss_per_poor_lighting"] * (1 - lq),
        "eye_strain": p["perf_loss_per_eye_strain"] * strain,
        "printer_particles": p["perf_loss_open_printers"] * open_share,
    }
    perf_index = math.prod(1 - min(v, 0.5) for v in loss.values())

    office_lpp = office_air_per_person(data, env)
    # sick_days_per_employee_year is today's building, so scale relative to today's ventilation
    sick = p["sick_days_per_employee_year"] * _sick_factor(p, office_lpp) / _sick_factor(p, ctx.get("office_lpp_today", office_lpp))

    coffee = [i for i in data["items"] if i["group"] == "coffee"]
    secs = _weighted([(i["units"], o_[sel[i["id"]]]["drivers"].get("seconds_per_drink", 60)) for i in coffee])
    amenity = _weighted([(i["units"], o_[sel[i["id"]]]["drivers"].get("amenity", 0.5)) for i in coffee])
    uses = _weighted([(i["units"], o_[sel[i["id"]]]["uses_per_person_day"] or 0) for i in coffee])
    vent_hum = _weighted([(data["item_by_id"][iid]["units"], o_[sel[iid]]["drivers"].get("humidity_control", 0))
                          for iid in data["vent_items"]])
    office_co2 = _weighted([(r["seats"], E[r["id"]]["co2_ppm"]) for r in desk_rooms])
    meet_co2 = _weighted([(r["seats"], E[r["id"]]["co2_ppm"]) for r in meet_rooms])
    comfort = (25 * max(0.0, min(1.0, (1600 - ((1 - m) * office_co2 + m * meet_co2)) / 1000))
               + 25 * max(0.0, min(1.0, 1 - overheat / 3))
               + 20 * lq + 15 * (1 - strain) + 10 * amenity + 5 * vent_hum)
    return {"perf_index": perf_index, "perf_losses": loss, "sick_days": sick,
            "coffee_minutes_per_day": secs * uses / 60, "comfort_score": comfort,
            "office_co2_ppm": office_co2, "meeting_co2_ppm": meet_co2,
            "classroom_co2_ppm": _weighted([(r["seats"], E[r["id"]]["co2_ppm"]) for r in teach_rooms]),
            "office_lps_per_person": office_lpp, "summer_overheating_degc": overheat,
            "lighting_quality": lq, "screen_quality": sq, "glare_control": gc, "eye_strain": strain}


def desk_capacity(data, sel):
    """Coupling: laptops enable hot-desking, so the same desks hold more people."""
    p = data["params"]
    comp = [i for i in data["items"] if i["group"] == "computers"]
    s = _weighted([(i["units"], data["options"][sel[i["id"]]]["drivers"].get("hot_desking", 0)) for i in comp])
    return data["desks"] * ((1 - s) + s / p["hot_desk_desks_per_person"])


def people_value(out_s, out_b, ctx):
    p = ctx["params"]
    daily = p["salary_cost_chf_year"] / p["workdays_per_year"]
    office_days = p["workdays_per_year"] * ctx["attendance"]     # attendance already includes sickness
    cap = p["max_total_perf_gain"]
    perf = max(-cap, min(cap, out_s["perf_index"] / out_b["perf_index"] - 1))
    minutes = (out_b["coffee_minutes_per_day"] - out_s["coffee_minutes_per_day"]) * p["productive_share_of_time_saved"]
    return {"perf_change": perf,
            "productivity_chf": perf * ctx["staff"] * office_days * daily,
            "sick_days_chf": (out_b["sick_days"] - out_s["sick_days"]) * ctx["staff"] * daily,
            "time_saved_chf": minutes / (p["hours_per_workday"] * 60) * ctx["staff"] * office_days * daily}


# ---------------------------------------------------------------- layer 4: money
def plan_money(data, plans, sel_final, horizon, params=None):
    p = params or data["params"]
    capex = [0.0] * (horizon + 1)
    assets = []
    for iid, installs in plans.items():
        item = data["item_by_id"][iid]
        for k, (t, oid, kind) in enumerate(installs):
            o = data["options"][oid]
            u = units_of(data, item, oid, sel_final)
            cost = u * ((o["purchase_chf_per_unit"] or 0) + (o["install_chf_per_unit"] or 0))
            if kind == "failure":
                cost *= 1 + p.get("failure_premium", 0)
            if item["group"] == "solar_pv" and oid != item["option"]:
                cost -= u * p["pv_subsidy_chf_per_kwp"]
            capex[t] += cost
            retire = installs[k + 1][0] if k + 1 < len(installs) else INF
            assets.append((t, cost, _life(o), min(t + _life(o), retire)))
    return capex, assets


def book_value(assets, t):
    return sum(c * (1 - (t - t0) / life) for t0, c, life, end in assets if t0 <= t < end and life != INF)


def maintenance(data, sel):
    return sum(units_of(data, i, sel[i["id"]], sel) * (data["options"][sel[i["id"]]]["maintenance_chf_per_unit_year"] or 0)
               for i in data["items"])


def payback(cums):
    if not cums or cums[-1][1] < 0:
        return None
    last_neg = max((t for t, (_, c, _) in enumerate(cums, start=1) if c < 0), default=0)
    if last_neg == 0 and cums[0][0] >= 0:
        return 0.0
    prev, _, cf = cums[last_neg]
    return last_neg + (-prev / cf if cf > 0 else 0.0)


_MEMO = {}


def _year_state(data, ctx, sel, ref):
    """Physical state is memoised (it does not depend on the electricity price); costs are not."""
    key = (id(data), tuple(sel.values()), ctx["staff"], ctx["cooling_mult"], ctx["heating_mult"],
           tuple(sorted(ctx["params"].items())), ref["internal_gains_kwh"])
    if key not in _MEMO:
        if len(_MEMO) > 20000:
            _MEMO.clear()
        _MEMO[key] = _physical_state(data, ctx, sel, ref)
    st = _MEMO[key]
    p = ctx["params"]
    e = st["energy"]
    costs = {
        "energy": e["grid_kwh"] * ctx["price"],
        "pv_export": -e["pv_export_kwh"] * p["pv_feed_in_chf_kwh"],
        "maintenance": st["maintenance"],
        "consumables": e["consumables_chf"],
        "rent": st["desk_shortfall"] * p["m2_per_extra_person"] * p["rent_chf_m2_year"],
    }
    return {**st, "costs": costs}


def _physical_state(data, ctx, sel, ref):
    e = energy(data, ctx, sel, ref["internal_gains_kwh"])
    env = environment(data, ctx, sel, e["thermal"]["cooling_kwh_th"], ref["thermal"]["cooling_kwh_th"])
    out = outcomes(data, ctx, sel, env)
    cap = desk_capacity(data, sel)
    return {"energy": e, "environment": env, "outcomes": out, "maintenance": maintenance(data, sel),
            "desk_capacity": cap, "desk_shortfall": max(0.0, ctx["staff"] - cap)}


def install_plans(data, scenario=None, future=None, horizon=None):
    """Who installs what, when, for every item: (choices, plans with the scenario, plans doing nothing).
    A plan is [(time, option_id, kind)], kind "planned" or "failure"; time t is the end of year t."""
    H = int(horizon or data["params"]["horizon_years"])
    choices = resolve(data, scenario)
    rem = (future or {}).get("remaining_life") or {}
    plans_b = {i["id"]: item_plan(data, i, None, H, rem.get(i["id"])) for i in data["items"]}
    plans_s = {i["id"]: item_plan(data, i, choices.get(i["id"]), H, rem.get(i["id"])) for i in data["items"]}
    return choices, plans_s, plans_b


def simulate(data, scenario=None, events_on=(), overrides=None, detail_years=(1,), future=None):
    """future (optional, from montecarlo.draw_future): sampled parameters, event timings,
    a yearly electricity price path and each unit's remaining life. Without it the run is deterministic."""
    overrides = {**(overrides or {}), **((future or {}).get("params") or {})}
    if future is not None:
        events_on = future["events"]
    p = {**data["params"], **overrides}
    H = int(p["horizon_years"])
    r = p["discount_rate_real"]
    choices, plans_s, plans_b = install_plans(data, scenario, future, H)
    final_s = {i["id"]: (plans_s[i["id"]][-1][1] if plans_s[i["id"]] else i["option"]) for i in data["items"]}
    final_s.update({iid: c[0] for iid, c in choices.items()})
    capex_b, assets_b = plan_money(data, plans_b, baseline(data), H, p)
    capex_s, assets_s = plan_money(data, plans_s, final_s, H, p)

    ref_ctx = year_context(data, 1, (), overrides)
    ref = energy(data, ref_ctx, baseline(data))
    cool_ref = ref["thermal"]["cooling_kwh_th"]
    lpp_today = office_air_per_person(data, environment(data, ref_ctx, baseline(data), cool_ref, cool_ref))
    upfront = capex_s[0] - capex_b[0]
    cash_s = p["opening_reserve_chf"] - capex_s[0]
    cash_b = p["opening_reserve_chf"] - capex_b[0]
    npv = {"cash": -upfront, "economic": -upfront}
    cum = {"cash": -upfront, "economic": -upfront}
    cums = {"cash": [], "economic": []}
    parts = defaultdict(float)
    parts["capex_and_residual"] = -upfront
    years, flags = [], []

    for t in range(1, H + 1):
        ctx = year_context(data, t, events_on, overrides)
        ctx["office_lpp_today"] = lpp_today
        if future is not None:
            ctx["price"] *= future["price_path"][t - 1]
        sel_b = {i["id"]: active_at(i, plans_b[i["id"]], t) for i in data["items"]}
        sel_s = {i["id"]: active_at(i, plans_s[i["id"]], t) for i in data["items"]}
        yb, ys = _year_state(data, ctx, sel_b, ref), _year_state(data, ctx, sel_s, ref)
        pv = people_value(ys["outcomes"], yb["outcomes"], ctx)
        saving = {k: yb["costs"][k] - ys["costs"][k] for k in ys["costs"]}
        residual = (book_value(assets_s, H) - book_value(assets_b, H)) if t == H else 0.0
        capex_part = -(capex_s[t] - capex_b[t]) + residual
        cf = sum(saving.values()) + capex_part
        cf_econ = cf + pv["productivity_chf"] + pv["sick_days_chf"] + pv["time_saved_chf"]
        op_s, op_b = sum(ys["costs"].values()), sum(yb["costs"].values())
        opening = cash_s
        cash_s = opening + p["other_operating_cf_chf_year"] - op_s - capex_s[t]
        cash_b = cash_b + p["other_operating_cf_chf_year"] - op_b - capex_b[t]
        d = (1 + r) ** t
        for view, x in (("cash", cf), ("economic", cf_econ)):
            prev = cum[view]
            cum[view] += x
            cums[view].append((prev, cum[view], x))
            npv[view] += x / d
        for k, v in saving.items():
            parts[k] += v / d
        parts["capex_and_residual"] += capex_part / d
        for k in ("productivity_chf", "sick_days_chf", "time_saved_chf"):
            parts[k.replace("_chf", "")] += pv[k] / d

        env = ys["environment"]
        for f, cap in env["floor_capacity_people"].items():
            if env["floor_population_peak"].get(f, 0) > cap:
                flags.append({"year": t, "type": "ventilation_over_capacity", "floor": f,
                              "people": round(env["floor_population_peak"][f]), "capacity": round(cap)})
        if ys["desk_shortfall"] > 0:
            flags.append({"year": t, "type": "desk_shortfall", "people": round(ys["desk_shortfall"], 1)})
        # Like-for-like replacements alone can run the reserve low, so a plan is only flagged
        # when it leaves less in the reserve than doing nothing would.
        low = p["min_reserve_chf"]
        if cash_s < low and cash_s < cash_b - 1e-6 and not any(f["type"] == "reserve_below_minimum" for f in flags):
            flags.append({"year": t, "type": "reserve_below_minimum", "reserve": round(cash_s), "minimum": low})
        if cash_b < low and not any(f["type"] == "reserve_below_minimum_without_upgrades" for f in flags):
            flags.append({"year": t, "type": "reserve_below_minimum_without_upgrades", "reserve": round(cash_b), "minimum": low})
        row = {"year": t, "cash_cf": cf, "economic_cf": cf_econ, "people_value": pv,
               "savings": saving, "capex": capex_s[t], "capex_baseline": capex_b[t], "residual_value": residual,
               "operating_cost": op_s, "operating_cost_baseline": op_b,
               "cumulative_cash_cf": cum["cash"], "cumulative_economic_cf": cum["economic"],
               "cash_opening": opening, "cash_closing": cash_s, "cash_closing_baseline": cash_b,
               "book_value": book_value(assets_s, t), "net_worth": cash_s + book_value(assets_s, t),
               "kwh": ys["energy"]["total_kwh"], "kwh_baseline": yb["energy"]["total_kwh"],
               "outcomes": ys["outcomes"], "outcomes_baseline": yb["outcomes"],
               "desk_capacity": ys["desk_capacity"], "staff": ctx["staff"]}
        row["price_chf_kwh"] = ctx["price"]
        if t in detail_years:
            row["state"], row["state_baseline"] = ys, yb
            row["selection"], row["selection_baseline"] = sel_s, sel_b
        years.append(row)

    if upfront > p["capex_budget_chf"]:
        flags.append({"year": 0, "type": "over_budget", "capex": round(upfront), "budget": p["capex_budget_chf"]})
    return {"choices": choices, "events": list(events_on), "capex_year0": upfront,
            "npv_cash": npv["cash"], "npv_economic": npv["economic"],
            "payback_cash": payback(cums["cash"]), "payback_economic": payback(cums["economic"]),
            "npv_breakdown": dict(parts), "years": years, "flags": flags,
            "plans": {k: v for k, v in plans_s.items() if v != plans_b[k]}}


# ---------------------------------------------------------------- stress test and uncertainty
def stress_test(data, scenario=None, event_id="hackathon_weekend", overrides=None):
    """Hour by hour on the hackathon weekend: can the ground floor's ventilation cope?

    Constant-volume units run on a workday timer, so on a weekend they are off unless facilities
    override them (param weekend_override_current_ahu). Units with CO2 demand control react to people.
    With no mechanical ventilation, only infiltration brings in fresh air."""
    p = {**data["params"], **(overrides or {})}
    e = data["events"][event_id]
    sel = baseline(data)
    for iid, (oid, _) in resolve(data, scenario).items():
        sel[iid] = oid
    floor = 0
    vent = [iid for iid, f in data["vent_items"].items() if f == floor]
    running = all(data["options"][sel[i]]["drivers"].get("co2_control", 0) for i in vent) or p["weekend_override_current_ahu"] >= 1
    airflow = sum(data["item_by_id"][i]["units"] * data["options"][sel[i]]["airflow_m3h"] for i in vent)
    volume = data["floor_vent_area"][floor] * p["floor_height_m"]
    air_m3h = (airflow if running else 0.0) + p["infiltration_ach"] * volume
    cap = air_m3h / p["fresh_air_m3h_per_person"]
    hours = []
    for h in range(24):
        people = e["value"] * data["schedule"]["hackathon"][h] * p["hackathon_floor0_share"]
        lpp = air_m3h / 3.6 / people if people else INF
        co2 = p["co2_outdoor_ppm"] + (p["co2_generation_lps_per_person"] * 1e6 / lpp if people else 0)
        hours.append({"hour": h, "people": people, "co2_ppm": co2, "over_capacity": people > cap})
    return {"ventilation_running": running, "capacity_people": cap, "peak_people": max(x["people"] for x in hours),
            "peak_co2_ppm": max(x["co2_ppm"] for x in hours),
            "hours_over_capacity_per_day": sum(x["over_capacity"] for x in hours), "hours": hours}


def bands(data, scenario=None, events_on=(), metric="npv_economic", overrides=None):
    base = dict(overrides or {})
    coupling = [k for k, m in data["param_meta"].items() if m["category"] == "coupling"]
    lo = {**base, **{k: data["ranges"][k][0] for k in coupling}}
    hi = {**base, **{k: data["ranges"][k][1] for k in coupling}}
    return {"weak": simulate(data, scenario, events_on, lo)[metric],
            "central": simulate(data, scenario, events_on, base)[metric],
            "strong": simulate(data, scenario, events_on, hi)[metric]}


def tornado(data, scenario=None, events_on=(), metric="npv_economic", top=None, overrides=None):
    base = dict(overrides or {})
    central = simulate(data, scenario, events_on, base)[metric]
    rows = []
    for k, (lo, hi) in data["ranges"].items():
        if lo is None or hi is None or lo == hi or data["param_meta"][k]["category"] == "future" or k in base:
            continue
        a = simulate(data, scenario, events_on, {**base, k: lo})[metric]
        b = simulate(data, scenario, events_on, {**base, k: hi})[metric]
        rows.append({"parameter": k, "low": lo, "high": hi, "at_low": a, "at_high": b, "swing": abs(b - a)})
    rows.sort(key=lambda x: -x["swing"])
    return {"central": central, "rows": rows[:top] if top else rows}


def breakeven(data, scenario=None, events_on=(), overrides=None, param="electricity_price_chf_kwh",
              lo=0.0, hi=None, tol=1e-4):
    """The value of one assumption at which the plan stops or starts paying off (NPV = 0), for cash and economic NPV.
    Returns, per metric, the value and whether the plan pays off above or below it; None if NPV keeps one sign in [lo, hi]."""
    base = dict(overrides or {})
    current = base.get(param, data["params"][param])
    hi = hi if hi is not None else max(current * 5, data["ranges"][param][1] * 3)

    def npv(v, metric):
        return simulate(data, scenario, events_on, {**base, param: v}, detail_years=())[metric]

    out = {"param": param, "current": current, "search_range": [lo, hi]}
    for metric in ("npv_cash", "npv_economic"):
        f_lo, f_hi = npv(lo, metric), npv(hi, metric)
        if (f_lo > 0) == (f_hi > 0):
            out[metric] = {"value": None, "pays_off": "always" if f_lo > 0 else "never"}
            continue
        a, b, fa = lo, hi, f_lo
        while b - a > tol:
            m = (a + b) / 2
            fm = npv(m, metric)
            if (fm > 0) == (fa > 0):
                a, fa = m, fm
            else:
                b = m
        out[metric] = {"value": (a + b) / 2, "pays_off": "above" if f_hi > 0 else "below",
                       "npv_at_current": npv(current, metric)}
    return out
